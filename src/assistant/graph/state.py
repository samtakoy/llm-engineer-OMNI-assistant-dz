"""
Состояние графа и схемы структурированного вывода.

Схем две, потому что этапа два. Ресёрч отвечает на вопрос «что известно и
откуда», изложение - на вопрос «в каком виде это подать». Их разделение не даёт
требованию стиля протекать в сбор фактов и наоборот.
"""

from typing import Annotated, Literal, TypedDict

from langchain_core.messages import AnyMessage
from langgraph.graph.message import add_messages
from pydantic import BaseModel, Field


class ResearchNotes(BaseModel):
    """
    Фактическая опора, собранная по источникам:

    facts дают проверяемый костяк,
    details - живую конкретику,
    gaps - границу, за которой начинается домысел,
    handoff - требования к подаче, замеченные на этапе поиска.
    """

    summary: str = Field(
        description = "О чём собранный материал и в каком порядке его логично излагать, без пересказа самих фактов"
    )
    facts: list[str] = Field(
        description = "Отдельные факты, каждый одним-двумя предложениями, только из найденных материалов"
    )
    details: list[str] = Field(
        description = "Наглядные важные подробности из материалов, например: цвета, звуки, запахи, размеры, сравнения"
    )
    gaps: list[str] = Field(
        description = "О чём в найденных материалах данных не нашлось"
    )
    handoff: str = Field(
        description = "Коротко важные заметки для писателя, который будет работать с собранными фактами"
    )
    confidence: Literal["высокая", "средняя", "низкая"] = Field(
        description = "Насколько найденные материалы подтверждают собранное"
    )
    sources: list[str] = Field(description = "Адреса страниц, на которых основаны факты")


class Section(BaseModel):
    """Один раздел итогового текста."""

    title: str = Field(
        description = (
            "Заголовок раздела на языке запроса пользователя, обычным регистром: "
            "заглавная только в начале и в именах собственных"
        )
    )
    content: str = Field(
        description = (
            "Текст раздела на языке запроса, в запрошенном пользователем стиле, "
            "обычным регистром без слов и фраз заглавными буквами"
        )
    )


class Answer(BaseModel):
    """
    Итоговый текст в том виде, который запросил пользователь.

    Схема намеренно нейтральна: разделами одинаково ложатся точки маршрута,
    шаги инструкции и пункты разбора. Что именно окажется разделом, решает
    запрос, а не код.
    """

    title: str = Field(
        description = (
            "Заголовок всего текста на языке запроса пользователя, обычным регистром: "
            "заглавная только в начале и в именах собственных"
        )
    )
    intro: str = Field(
        description = (
            "Вступление на языке запроса пользователя, обычным регистром "
            "без слов и фраз заглавными буквами"
        )
    )
    sections: list[Section] = Field(description = "Разделы по порядку изложения")
    closing: str = Field(
        description = (
            "Завершение на языке запроса пользователя, обычным регистром "
            "без слов и фраз заглавными буквами"
        )
    )


class ResearchState(TypedDict):
    """
    Состояние прогона.

    Поля:
        question: исходный вопрос пользователя.
        messages: история диалога с моделью, включая вызовы инструментов.
        narrator_prompt: блок про рассказчика для узла compose; None - изложение
            без персонажа.
        notes: фактическая опора, появляется на узле collect.
        answer: итоговый текст, появляется на узле compose.
    """

    question: str
    messages: Annotated[list[AnyMessage], add_messages]
    narrator_prompt: str | None
    notes: ResearchNotes | None
    answer: Answer | None
